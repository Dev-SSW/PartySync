CREATE TABLE push_subscription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_member_id BIGINT NOT NULL REFERENCES group_member(id) ON DELETE CASCADE,
    user_session_id BIGINT REFERENCES user_session(id) ON DELETE CASCADE,
    endpoint_hash VARCHAR(64) NOT NULL,
    endpoint VARCHAR(2048) NOT NULL,
    p256dh VARCHAR(128) NOT NULL,
    auth VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uk_push_member_endpoint UNIQUE(group_member_id, endpoint_hash)
);
CREATE INDEX ix_push_session ON push_subscription(user_session_id);

-- 변경과 같은 트랜잭션에서 기록하므로 저장 실패 시 알림도 취소된다.
-- 자동 저장은 작성자·수신 기기별로 하나로 모으고 재시작 후에도 발송한다.
CREATE TABLE push_delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES group_member(id) ON DELETE CASCADE,
    subscription_id BIGINT NOT NULL REFERENCES push_subscription(id) ON DELETE CASCADE,
    due_at TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_push_delivery UNIQUE(actor_id, subscription_id)
);
CREATE INDEX ix_push_delivery_due ON push_delivery(due_at);
