CREATE TABLE groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    invite_code VARCHAR(128) NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_groups_invite_code UNIQUE (invite_code),
    CONSTRAINT ck_groups_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_groups_invite_code CHECK (length(btrim(invite_code)) > 0)
);

CREATE TABLE group_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    nickname VARCHAR(50) NOT NULL,
    role VARCHAR(16) NOT NULL,
    access_token_hash VARCHAR(255) NOT NULL,
    joined_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_member_group FOREIGN KEY (group_id) REFERENCES groups(id),
    CONSTRAINT uk_member_group_nickname UNIQUE (group_id, nickname),
    -- Composite keys below let posts enforce group ownership at the database boundary.
    CONSTRAINT uk_member_id_group UNIQUE (id, group_id),
    CONSTRAINT ck_member_nickname CHECK (length(btrim(nickname)) > 0),
    CONSTRAINT ck_member_role CHECK (role IN ('OWNER', 'MEMBER')),
    CONSTRAINT ck_member_token_hash CHECK (length(btrim(access_token_hash)) > 0)
);

CREATE TABLE weekly_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_member_id BIGINT NOT NULL,
    day_of_week VARCHAR(9) NOT NULL,
    start_minute INTEGER NOT NULL,
    end_minute INTEGER NOT NULL,
    CONSTRAINT fk_weekly_member FOREIGN KEY (group_member_id) REFERENCES group_member(id),
    CONSTRAINT ck_weekly_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_weekly_minutes CHECK (0 <= start_minute AND start_minute < end_minute AND end_minute <= 1440),
    CONSTRAINT uk_weekly_exact_slot UNIQUE (group_member_id, day_of_week, start_minute, end_minute)
);

CREATE TABLE availability_override (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_member_id BIGINT NOT NULL,
    target_date DATE NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_override_member FOREIGN KEY (group_member_id) REFERENCES group_member(id),
    CONSTRAINT uk_override_member_date UNIQUE (group_member_id, target_date)
);

CREATE TABLE availability_override_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    availability_override_id BIGINT NOT NULL,
    start_minute INTEGER NOT NULL,
    end_minute INTEGER NOT NULL,
    CONSTRAINT fk_slot_override FOREIGN KEY (availability_override_id)
        REFERENCES availability_override(id) ON DELETE CASCADE,
    CONSTRAINT ck_slot_minutes CHECK (0 <= start_minute AND start_minute < end_minute AND end_minute <= 1440),
    CONSTRAINT uk_override_exact_slot UNIQUE (availability_override_id, start_minute, end_minute)
);

CREATE TABLE game_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_category_group FOREIGN KEY (group_id) REFERENCES groups(id),
    CONSTRAINT uk_category_group_name UNIQUE (group_id, name),
    CONSTRAINT uk_category_id_group UNIQUE (id, group_id),
    CONSTRAINT ck_category_name CHECK (length(btrim(name)) > 0)
);

CREATE TABLE post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    game_category_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_post_group FOREIGN KEY (group_id) REFERENCES groups(id),
    CONSTRAINT fk_post_category_group FOREIGN KEY (game_category_id, group_id)
        REFERENCES game_category(id, group_id),
    CONSTRAINT fk_post_author_group FOREIGN KEY (author_id, group_id)
        REFERENCES group_member(id, group_id),
    CONSTRAINT ck_post_title CHECK (length(btrim(title)) > 0)
);

CREATE INDEX ix_post_group_created ON post(group_id, created_at DESC, id DESC);
CREATE INDEX ix_post_category_group ON post(game_category_id, group_id);
CREATE INDEX ix_post_author_group ON post(author_id, group_id);
