-- 기존 그룹·멤버·일정·게시글은 유지하고 선택적인 계정 연결을 추가한다.
CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(32) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_user_login_id UNIQUE (login_id),
    CONSTRAINT ck_user_login_id CHECK (login_id ~ '^[a-z0-9][a-z0-9_]{3,31}$'),
    CONSTRAINT ck_user_password_hash CHECK (length(password_hash) > 0)
);

ALTER TABLE group_member ADD COLUMN user_id BIGINT;
ALTER TABLE group_member ADD CONSTRAINT fk_member_user FOREIGN KEY (user_id) REFERENCES user_account(id);
ALTER TABLE group_member ADD CONSTRAINT uk_member_user_group UNIQUE (user_id, group_id);
ALTER TABLE group_member ALTER COLUMN access_token_hash DROP NOT NULL;
-- 계정 연결 후에는 과거 비회원 토큰으로 인증할 수 없다.
ALTER TABLE group_member ADD CONSTRAINT ck_member_auth_type CHECK (
    (user_id IS NULL AND access_token_hash IS NOT NULL) OR
    (user_id IS NOT NULL AND access_token_hash IS NULL)
);

CREATE TABLE user_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(id),
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_user_session_token UNIQUE (token_hash),
    CONSTRAINT ck_user_session_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_user_session_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT uk_user_session_id_user UNIQUE (id, user_id)
);
CREATE INDEX ix_user_session_user ON user_session(user_id);
CREATE INDEX ix_user_session_expiry ON user_session(expires_at);

CREATE TABLE member_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_member_id BIGINT NOT NULL REFERENCES group_member(id),
    user_session_id BIGINT NOT NULL REFERENCES user_session(id),
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_member_session_token UNIQUE (token_hash),
    CONSTRAINT ck_member_session_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_member_session_hash CHECK (token_hash ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_member_session_member ON member_session(group_member_id);
CREATE INDEX ix_member_session_parent ON member_session(user_session_id);
CREATE INDEX ix_member_session_expiry ON member_session(expires_at);
